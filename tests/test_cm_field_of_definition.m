// test_cm_field_of_definition.m
// Regression test for FieldsOfDefinitionOfCMPoint (src/fields_of_definition.m).
//
// Q(P) is the subfield of the ring class field H_R fixed by sigma = c . sigma_a
// (c = complex conjugation, [a] in Pic(R)/Pic(R)^2 satisfying the quaternion
// condition).  See arXiv:math/0612732v2, Gonzalez-Rotger, Appendix.
//
// It is single-valued except for one genuine source of multiplicity:
//   GR Remark (uniqueness): [a] is determined by the quaternion condition only
//   when f = 1.  For f > 1 several classes can satisfy it, each giving a field.
//   Pinned below by N = 377, d = -36 (f = 3) -> {Q(sqrt(-3)), Q(sqrt(3))}.
//
// There is a second, spurious source that an earlier implementation reported as
// real: enumerating every order-2 automorphism of H_R restricting to complex
// conjugation on K.  When Pic(R) has exponent > 2, every c . tau for tau in
// Gal(H_R/K) = Pic(R) has order 2 and restricts to conjugation on K, so that
// enumeration returns the whole coset, exactly h candidates, every time; and
// then dedups.  The answer it produced was the union over levels, which always
// contains the right field and so looked correct.
//
// The current implementation instead works inside the Atkin-Lehner-fixed field
// A_abs, so it is level-aware: d = -39 gives Q(sqrt(13)) at N = 286 but
// Q(sqrt(-3)) at N = 26.  The old approach could not express that distinction.
//
// Expected values below are generated by scripts/gen_cm_field_expectations.m from
// ShimuraCurveALQuotients/SchoferFormula.m (intrinsic FieldsOfDefinitionOfCMPointFast),
// specialised to D = 1, W = all of Divisors(N).  This test itself has no dependency
// on that repo.
//
// Run with: tests/run.sh test_cm_field_of_definition

load "src/AtkinLehner.m";
load "tests/assertions.m";

results := NewResults();

// Tag a field of degree <= 2 by the squarefree part of its discriminant
// (1 for Q); tag higher-degree fields by 10000*degree.  Must match Tag() in
// scripts/gen_cm_field_expectations.m.
function FieldTag(F)
    if Degree(F) eq 1 then return 1; end if;
    if Degree(F) gt 2 then return 10000*Degree(F); end if;
    return Squarefree(Discriminant(MaximalOrder(F)));
end function;

function DistinctTags(flds)
    return Sort(SetToSequence({FieldTag(F) : F in flds}));
end function;

