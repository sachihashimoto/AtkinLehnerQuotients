// FieldTag collapses every field of degree > 2 to 10000*Degree(F), so tags
// alone cannot distinguish one degree-8 field from several, and "several
// where there should be one" is exactly the bug this port fixes (see header).
// Assert #flds alongside the tags so the high-degree rows stay discriminating
// instead of silently passing on a wrong count with matching tags.
rc := AssociativeArray();
for c in cases do
    N := c[1]; d := c[2]; expected_n := c[3]; expected := c[4];
    flds, rc := FieldsOfDefinitionOfCMPoint(N, d : rc_cache := rc);
    got := DistinctTags(flds);
    AssertEqual(~results, (#flds eq expected_n) and (got eq expected), true,
        Sprintf("N=%o, d=%o: %o field(s) with tags %o (got %o with %o)",
            N, d, expected_n, expected, #flds, got));
end for;

// Proposition 5.6 early exit still returns the empty list.
flds_empty, _ := FieldsOfDefinitionOfCMPoint(26, -32);
AssertEqual(~results, #flds_empty, 0,
    "N=26, d=-32: Prop 5.6 rules out a CM point, empty list");

// All candidates for a given (N, d) must share one degree; the degree is
// well defined even when the field is not, which is what
// DegreeOfFieldOfDefinitionOfCMPoint relies on.  Only c[1], c[2] are used
// here; "#flds eq 0" below corresponds to "c[3] = 0" (no CM point) above.
printf "\n=== degree is single-valued and agrees with the fast degree function ===\n";
for c in cases do
    N := c[1]; d := c[2];
    flds, rc := FieldsOfDefinitionOfCMPoint(N, d : rc_cache := rc);
    if #flds eq 0 then continue; end if;
    degs := {Degree(F) : F in flds};
    fast := DegreeOfFieldOfDefinitionOfCMPoint(N, d);
    AssertEqual(~results, #degs eq 1 and fast in degs, true,
        Sprintf("N=%o, d=%o: all candidates have degree %o (fast function says %o)",
            N, d, degs, fast));
end for;

Report(~results, "test_cm_field_of_definition");
