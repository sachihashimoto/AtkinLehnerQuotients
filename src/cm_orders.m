// src/cm_orders.m
//
// Class-number bookkeeping: which imaginary quadratic orders can contribute a
// rational, or low-degree, CM point on X_0(N)*.
//
// Entry points:  CMOrdersForAL(m)     the orders attached to w_m
//                CMClassLists() / CMClassListsDeg2()     discriminant tables
//                bounding the degree-1 and degree-2 searches
//
// Also defines omega(N), the number of distinct prime divisors of N, used
// throughout the library; this module loads before everything that calls it.
//
// Self-contained: depends on nothing else in the repo.

omega := function(N)
    return #[p : p in PrimeDivisors(N)];
end function;

function SquarePart(m)
// Square part of m
    fac := Factorization(m);
    prod := 1;
    for f in fac do
        if f[2] ge 2 then
            if IsEven(f[2]) then
                prod *:= Integers()!(f[1]^(Integers()!f[2]/2));
            else
                prod *:= Integers()!(f[1]^(Integers()!(f[2]-1)/2));
            end if;
        end if;
    end for;
    return prod;
end function;

function CMOrdersForAL(m)
    // CM orders whose points can be fixed by w_m
    if m eq 2 then
        return [MaximalOrder(QuadraticField(-1)), MaximalOrder(QuadraticField(-2))];
    elif m mod 4 eq 3 then
        F<a> := QuadraticField(-m);
        sqm := SquarePart(m);
        sqrt_minus_m := sqm * a;
        O := MaximalOrder(F);
        alpha := (1 + sqrt_minus_m) / 2;
        return [sub<O | alpha>, sub<O | 2*alpha>];
    else
        F<a> := QuadraticField(-m);
        sqm := SquarePart(m);
        sqrt_minus_m := sqm * a;
        O := MaximalOrder(F);
        return [sub<O | sqrt_minus_m>];
    end if;
end function;

